export function localizeAnalysisText(value: string | undefined | null, locale: Locale): string {
  if (!value || locale === "en") return value ?? "";
  const phrases = COPY[locale];
  if (!phrases) return value;
  let output = value;
  for (const [source, translated] of phrases) {
    output = output.split(source).join(translated);
  }
  return output;
}
